  void _initTree() {
    for (int i = n + 1; i <= n + 256; i++) {
      rSon[i] = nodeNil;
    }
    for (int i = 0; i < n; i++) {
      dad[i] = nodeNil;
    }
  }

  void _insertNode(int rNode) {
    int i, p, c;
    bool geq = true;

    p = n + 1 + textBuf[rNode];
    rSon[rNode] = nodeNil;
    lSon[rNode] = nodeNil;
    matchLength = 0;
    while (true) {
      if (geq) {
        if (rSon[p] == nodeNil) {
          rSon[p] = rNode;
          dad[rNode] = p;
          return;
        } else {
          p = rSon[p];
        }
      } else {
        if (lSon[p] == nodeNil) {
          lSon[p] = rNode;
          dad[rNode] = p;
          return;
        } else {
          p = lSon[p];
        }
      }
      i = 1;
      while ((i < f) && (textBuf[rNode + i] == textBuf[p + i])) {
        i++;
      }

      geq = (textBuf[rNode + i] >= textBuf[p + i]) || (i == f);

      if (i > threshold) {
        if (i > matchLength) {
          matchPosition = ((rNode - p) & (n - 1)) - 1;
          matchLength = i;
          if (matchLength >= f) break;
        }
        if (i == matchLength) {
          c = ((rNode - p) & (n - 1)) - 1;
          if (c < matchPosition) matchPosition = c;
        }
      }
    }

    dad[rNode] = dad[p];
    lSon[rNode] = lSon[p];
    rSon[rNode] = rSon[p];
    dad[lSon[p]] = rNode;
    dad[rSon[p]] = rNode;
    if (rSon[dad[p]] == p) {
      rSon[dad[p]] = rNode;
    } else {
      lSon[dad[p]] = rNode;
    }
    dad[p] = nodeNil;
  }

  void _deleteNode(int p) {
    int q;
    if (dad[p] == nodeNil) return;

    if (rSon[p] == nodeNil) {
      q = lSon[p];
    } else {
      if (lSon[p] == nodeNil) {
        q = rSon[p];
      } else {
        q = lSon[p];
        if (rSon[q] != nodeNil) {
          do {
            q = rSon[q];
          } while (rSon[q] != nodeNil);
          rSon[dad[q]] = lSon[q];
          dad[lSon[q]] = dad[q];
          lSon[q] = lSon[p];
          dad[lSon[p]] = q;
        }
        rSon[q] = rSon[p];
        dad[rSon[p]] = q;
      }
    }
    dad[q] = dad[p];
    if (rSon[dad[p]] == p) {
      rSon[dad[p]] = q;
    } else {
      lSon[dad[p]] = q;
    }
    dad[p] = nodeNil;
  }

  int _getBit() {
    while (getLen <= 8) {
      getBuf = (getBuf | (_getc() << (8 - getLen))) & 0xFFFF;
      getLen += 8;
    }
    const auto retVal = (getBuf >> 15) & 0x1;
    getBuf = (getBuf << 1) & 0xFFFF;
    getLen--;
    return retVal;
  }

  int _getByte() {
    while (getLen <= 8) {
      getBuf = (getBuf | (_getc() << (8 - getLen))) & 0xFFFF;
      getLen += 8;
    }
    const auto retVal = _hi(getBuf) & 0xFF;
    getBuf = (getBuf << 8) & 0xFFFF;
    getLen -= 8;
    return retVal;
  }

  void _putcode(int nBits, int c) {
    putBuf = (putBuf | (c >> putLen)) & 0xFFFF;
    putLen += nBits;
    if (putLen >= 8) {
      _putc(_hi(putBuf) & 0xFF);
      putLen -= 8;
      if (putLen >= 8) {
        _putc(_lo(putBuf) & 0xFF);
        codeSize += 2;
        putLen -= 8;
        putBuf = (uint32_t(c) << (nBits - putLen)) & 0xFFFF;
      } else {
        putBuf = _swap(putBuf & 0xFF);
        codeSize += 1;
      }
    }
  }

  void _startHuff() {
    int i, j;
    for (i = 0; i < nChar; i++) {
      freq[i] = 1;
      son[i] = i + t;
      parent[i + t] = i;
    }
    i = 0;
    j = nChar;
    while (j <= r) {
      freq[j] = (freq[i] + freq[i + 1]) & 0xFFFF;
      son[j] = i;
      parent[i] = j;
      parent[i + 1] = j;
      i += 2;
      j++;
    }
    freq[t] = 0xFFFF;
    parent[r] = 0;
  }

  void _reconst() {
    int i, j = 0, k, fr, nn;
    for (i = 0; i < t; i++) {
      if (son[i] >= t) {
        freq[j] = (freq[i] + 1) >> 1;
        son[j] = son[i];
        j++;
      }
    }
    i = 0;
    j = nChar;
    while (j < t) {
      k = i + 1;
      fr = (freq[i] + freq[k]) & 0xFFFF;
      freq[j] = fr;
      k = j - 1;
      while (fr < freq[k]) {
        k--;
      }
      k++;
      for (nn = j; nn >= k + 1; nn--) {
        freq[nn] = freq[nn - 1];
        son[nn] = son[nn - 1];
      }
      freq[k] = fr;
      son[k] = i;
      i += 2;
      j++;
    }
    for (i = 0; i < t; i++) {
      k = son[i];
      parent[k] = i;
      if (k < t) parent[k + 1] = i;
    }
  }

  void _update(int c) {
    int i, j, k, nn;
    if (freq[r] == maxFreq) _reconst();
    c = parent[c + t];
    do {
      freq[c]++;
      k = freq[c];
      nn = c + 1;
      if (k > freq[nn]) {
        while (k > freq[nn + 1]) {
          nn++;
        }
        freq[c] = freq[nn];
        freq[nn] = k;

        i = son[c];
        parent[i] = nn;
        if (i < t) parent[i + 1] = nn;
        j = son[nn];
        son[nn] = i;

        parent[j] = c;
        if (j < t) parent[j + 1] = c;
        son[c] = j;

        c = nn;
      }
      c = parent[c];
    } while (c != 0);
  }

  void _encodeChar(int c) {
    int code = 0, k = parent[c + t];
    int len = 0;
    do {
      code >>= 1;
      if ((k & 1) > 0) code += 0x8000;
      len++;
      k = parent[k];
    } while (k != r);
    _putcode(len, code);
    _update(c);
  }

  void _encodePosition(int c) {
    const auto i = c >> 6;
    _putcode(_pLen[i], _pCode[i] << 8);
    _putcode(6, (c & 0x3F) << 10);
  }

  void _encodeEnd() {
    if (putLen > 0) {
      _putc(_hi(putBuf));
      codeSize++;
    }
  }

  int _decodeChar() {
    int c = son[r];
    while (c < t) {
      c = son[c + _getBit()];
    }
    c -= t;
    _update(c);
    return c & 0xFFFF;
  }

  int _decodePosition() {
    int i = _getByte();
    const auto c = (_dCode[i] << 6) & 0xFFFF;
    int j = _dLen[i];
    j -= 2;
    while (j > 0) {
      j--;
      i = ((i << 1) | _getBit()) & 0xFFFF;
    }
    return c | (i & 0x3F);
  }

